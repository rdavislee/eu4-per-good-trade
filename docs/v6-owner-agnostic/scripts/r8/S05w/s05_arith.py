import math
def trunc2(x):
    return math.floor(x*100)/100

print("6*0.0833333 =", 6*0.0833333, "trunc2 =", trunc2(6*0.0833333))
print("2*0.0833333 =", 2*0.0833333, "trunc2 =", trunc2(2*0.0833333))
print("0.49*12 =", 0.49*12)
print("0.16*12 =", 0.16*12)
print("0.49*1.25 =", 0.49*1.25, "trunc2 =", trunc2(0.49*1.25))
print("untrunc: 6*0.0833333=", 6*0.0833333, "*1.25=", 6*0.0833333*1.25, "trunc2=", trunc2(6*0.0833333*1.25))
print("0.80*4.00 =", 0.80*4.00, "*1.10 =", 0.80*4.00*1.10)
print("divisor bounds: 3.52/0.30 =", 3.52/0.30, " 3.52/0.29 =", 3.52/0.29)
